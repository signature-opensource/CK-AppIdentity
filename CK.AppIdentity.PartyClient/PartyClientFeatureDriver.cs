using CK.Core;
using CK.Setup;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading.Tasks;

namespace CK.AppIdentity;

/// <summary>
/// The "PartyClient" feature: the clients of the local parties (the root and the tenant domains, initial or dynamic).
/// It is allowed by default: <c>"PartyClient": false</c> makes a party without clients.
/// <para>
/// A client is <b>declared</b> by a party, in its "Local:PartyClient:{Name}" section: only the configuration says which
/// party has which client. A client is a bag of client features (<see cref="ClientFeature"/>): the keys of its section
/// are its features ("NgApp", "Hosting"...), each one created by its <see cref="IClientFeatureDriver"/>, plus its type
/// set ("Types" and "ExcludedTypes": compile time keys, accepted and ignored). A feature without configuration is declared
/// by <c>true</c> (<c>"NgApp": true</c>).
/// </para>
/// <list type="bullet">
///   <item>A key of a client that is no feature of the application is an error; a client without feature is an error.</item>
///   <item>The requirements of the features are checked (see <see cref="PartyComponentDirectory.CheckScope"/>): a
///   required feature of the party must be allowed by the party, a required abstraction implemented by a feature of the
///   client, a unique abstraction implemented once.</item>
///   <item>The features are created in their order (a feature after the ones it requires), then their options are
///   selected from their section, created from the services and given to them (see <see cref="ClientFeature.Options"/>).</item>
/// </list>
/// </summary>
[PartyFeature( "PartyClient", TypeActivation.ByDefault )]
public sealed class PartyClientFeatureDriver : ApplicationIdentityFeatureDriver
{
    /// <summary>
    /// The configuration section of the clients, in the "Local" section of a local party.
    /// </summary>
    public const string PartyClientSectionName = "PartyClient";

    readonly Dictionary<string, IClientFeatureDriver> _drivers;
    readonly IServiceProvider _services;
    readonly PartyComponentDirectory _componentDirectory;
    readonly PartyComponentOptionDirectory? _optionDirectory;

    /// <summary>
    /// Initializes a new <see cref="PartyClientFeatureDriver"/>.
    /// </summary>
    /// <param name="s">The application identity service.</param>
    /// <param name="drivers">The drivers of the client features.</param>
    /// <param name="services">The services from which the options are created and the party features found.</param>
    /// <param name="optionDirectory">
    /// The options of the party components (generated by the engine): it is null only without it, and the features then
    /// have no option.
    /// </param>
    public PartyClientFeatureDriver( ApplicationIdentityService s,
                                     IEnumerable<IClientFeatureDriver> drivers,
                                     IServiceProvider services,
                                     PartyComponentOptionDirectory? optionDirectory = null )
        : base( s )
    {
        _drivers = new Dictionary<string, IClientFeatureDriver>( StringComparer.OrdinalIgnoreCase );
        _componentDirectory = s.ComponentDirectory;
        foreach( var d in drivers )
        {
            var name = _componentDirectory.Find( d.FeatureType )?.FeatureName;
            Throw.CheckState( $"The client feature '{d.FeatureType:N}' is not a named party component of the application.", name != null );
            _drivers[name] = d;
        }
        _services = services;
        _optionDirectory = optionDirectory;
    }

    /// <summary>
    /// Gets the keys of a client section that are its type set: compile time keys, ignored at run time.
    /// </summary>
    public static IReadOnlySet<string> TypeSetKeys { get; } = new HashSet<string>( StringComparer.OrdinalIgnoreCase ) { "Types", "ExcludedTypes" };

    /// <inheritdoc />
    protected override Task<bool> SetupAsync( FeatureLifetimeContext context )
    {
        bool success = true;
        foreach( var local in context.GetAllLocals() )
        {
            success &= SetupLocal( context.Monitor, local );
        }
        return Task.FromResult( success );
    }

    /// <inheritdoc />
    protected override Task<bool> SetupDynamicRemoteAsync( FeatureLifetimeContext context, IOwnedParty party )
    {
        // A dynamic tenant domain has its clients. A remote has none: its clients are known by its description.
        if( party is not ILocalParty local ) return Task.FromResult( true );
        return Task.FromResult( SetupLocal( context.Monitor, local ) );
    }

    /// <inheritdoc />
    protected override Task TeardownDynamicRemoteAsync( FeatureLifetimeContext context, IOwnedParty party ) => Task.CompletedTask;

    /// <inheritdoc />
    protected override Task TeardownAsync( FeatureLifetimeContext context ) => Task.CompletedTask;

    /// <summary>
    /// Contributes the clients of the party to its description (<see cref="PartyDescription.ClientApplications"/>): the
    /// clients that have a <see cref="PartyClient.Description"/>. The clients of a party are created by its setup: they
    /// never change.
    /// </summary>
    /// <param name="party">The local party to describe.</param>
    /// <param name="builder">The description builder.</param>
    protected override void ContributeDescription( ILocalParty party, PartyDescription.Builder builder )
    {
        var feature = party.GetFeature<PartyClientFeature>();
        if( feature == null ) return;
        foreach( var c in feature.Clients )
        {
            if( c.Description is { } d ) builder.AddClientApplication( d );
        }
    }

    bool SetupLocal( IActivityMonitor monitor, ILocalParty local )
    {
        // Declaring clients declares the feature (its section): a party without the feature has no clients.
        if( !IsAllowedFeature( local ) ) return true;
        // The declaration is read on the party only (no "Defaults"): a party declares its own clients.
        var section = local.LocalConfiguration.Configuration.TryGetSection( PartyClientSectionName );
        var declared = section?.GetChildren() ?? [];
        bool success = true;
        var clients = new List<PartyClient>( declared.Count );
        foreach( var c in declared )
        {
            var client = new PartyClient( local, c.Key, c );
            if( TrySetupClient( monitor, local, client ) ) clients.Add( client );
            else success = false;
        }
        if( !success ) return false;
        local.AddFeature( new PartyClientFeature( local, clients ) );
        return true;
    }

    bool TrySetupClient( IActivityMonitor monitor, ILocalParty local, PartyClient client )
    {
        bool success = true;
        var declared = new List<(IClientFeatureDriver Driver, ImmutableConfigurationSection Section)>();
        var keys = new HashSet<string>( StringComparer.OrdinalIgnoreCase );
        foreach( var k in client.Configuration.GetChildren() )
        {
            if( TypeSetKeys.Contains( k.Key ) ) continue;
            if( _drivers.TryGetValue( k.Key, out var driver ) )
            {
                keys.Add( k.Key );
                // A feature is declared by its section, or by true when it has no configuration; false turns off a
                // feature that is not optional (a Required one can't be turned off).
                var activation = _componentDirectory.Find( driver.FeatureType )!.Activation;
                // The types drive: a declared feature must be a member of the client's set.
                if( !_componentDirectory.IsMember( client.Name, driver.FeatureType )
                    && !string.Equals( k.Value, "false", StringComparison.OrdinalIgnoreCase ) )
                {
                    monitor.Error( $"The client feature \"{k.Path}\" is not a member of the type set of the {client}: the types drive, a key doesn't bring its feature in (add its type to the \"Types\" of the client)." );
                    success = false;
                }
                else if( k.Value == null )
                {
                    declared.Add( (driver, k) );
                }
                else if( bool.TryParse( k.Value, out var b ) )
                {
                    if( b )
                    {
                        if( activation != TypeActivation.Optional )
                        {
                            monitor.Warn( $"Redundant \"{k.Path}\" = true: the client feature is {(activation == TypeActivation.Required ? "required" : "there by default")}." );
                        }
                        declared.Add( (driver, k) );
                    }
                    else if( activation == TypeActivation.Required )
                    {
                        monitor.Error( $"The client feature \"{k.Path}\" is required: it can't be turned off." );
                        success = false;
                    }
                    else if( activation == TypeActivation.Optional )
                    {
                        monitor.Warn( $"Redundant \"{k.Path}\" = false: the client feature is optional, it is off unless declared." );
                    }
                }
                else
                {
                    monitor.Error( $"Invalid \"{k.Path}\" = '{k.Value}': a client feature is declared by true or by its section (false turns off a feature that is there by default)." );
                    success = false;
                }
            }
            else
            {
                monitor.Error( $"Unknown \"{k.Path}\": the keys of a client are its features ({(_drivers.Count > 0 ? _drivers.Keys.Order().Concatenate() : "no client feature in this application")}) and its type set (Types, ExcludedTypes)." );
                success = false;
            }
        }
        if( !success ) return false;
        // The features that are not optional are there without their key (their configuration is empty).
        foreach( var (name, driver) in _drivers )
        {
            if( !keys.Contains( name )
                && _componentDirectory.Find( driver.FeatureType )!.Activation != TypeActivation.Optional
                && _componentDirectory.IsMember( client.Name, driver.FeatureType ) )
            {
                declared.Add( (driver, client.Configuration.GetSection( name )) );
            }
        }
        if( declared.Count == 0 )
        {
            monitor.Error( $"The {client} has no feature." );
            return false;
        }
        if( !_componentDirectory.CheckScope( monitor, client.ToString(), declared.Select( d => d.Driver.FeatureType ).ToList(), IsAvailableInParty ) )
        {
            return false;
        }
        declared.Sort( ( a, b ) => _componentDirectory.IndexOf( a.Driver.FeatureType ).CompareTo( _componentDirectory.IndexOf( b.Driver.FeatureType ) ) );
        foreach( var (driver, section) in declared )
        {
            // The configuration model of the feature: read from its section (a bare true without keys has none), its options
            // reserved.
            object? model = null;
            if( _componentDirectory.Find( driver.FeatureType )!.Model is { } description )
            {
                var collector = new UserMessageCollector( new CurrentCultureInfo( new TranslationService(), NormalizedCultureInfo.CodeDefault ) );
                var reserved = _optionDirectory?.GetOptions( driver.FeatureType ).Select( o => o.Name ) ?? [];
                model = ConfigurationModelReader.TryRead( description, [section.Value == null || section.GetChildren().Any() ? section : null], section.Path, collector, reserved );
                collector.DumpLogs( monitor );
                if( model == null )
                {
                    success = false;
                    continue;
                }
            }
            var f = driver.Create( monitor, client, section, model );
            if( f == null )
            {
                success = false;
                continue;
            }
            if( f.GetType() != driver.FeatureType || f.Client != client )
            {
                monitor.Error( $"The driver '{driver.GetType().ToCSharpName()}' created '{f}' instead of a '{driver.FeatureType.Name}' of the {client}." );
                success = false;
                continue;
            }
            f._name = _componentDirectory.Find( driver.FeatureType )!.FeatureName!;
            if( !TrySetOptions( monitor, local, f, section ) )
            {
                success = false;
                continue;
            }
            // The next features find it (a feature requires the ones before it).
            client.AddFeature( f );
        }
        if( !success ) return false;
        client.Complete();
        return true;

        // A required feature driver of the party: allowed by the party.
        bool IsAvailableInParty( Type required ) => typeof( ApplicationIdentityFeatureDriver ).IsAssignableFrom( required )
                                                    && _services.GetService( required ) is ApplicationIdentityFeatureDriver d
                                                    && d.IsAllowedFeature( local );
    }

    // Selects the options of a created feature from its section, creates them and gives them to the feature.
    bool TrySetOptions( IActivityMonitor monitor, ILocalParty local, ClientFeature feature, ImmutableConfigurationSection section )
    {
        if( _optionDirectory == null ) return true;
        if( !_optionDirectory.TryCreate( monitor, feature.GetType(), section, _services, out var options, o => o.FindMissingFeature( _services, local ) ) ) return false;
        feature.Options = options;
        return true;
    }
}

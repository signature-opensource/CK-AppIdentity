<#
.SYNOPSIS
    Starts all the parties of this development solution in Development, waits until they are ready, and stops them
    when Enter is pressed.

.DESCRIPTION
    Generated by CK.AppIdentity.Hosting: this file is copied in "#Dev" by the build of the parties. Don't edit it.

    1. Reads the manifests of the parties ("#Dev/Parties/*.json", written by their build).
    2. Unless -SkipBuild: builds each party (dotnet build). The TypeScript integration of the build installs the
       packages of the client applications ("yarn install") when needed.
    3. Starts each party in its own window, in the Development environment (DOTNET_ENVIRONMENT).
    4. Waits until every party is ready: its "DevRunningStatus.json" (in "#Dev/Store", written by the "DevRunningStatus"
       feature of CK.AppIdentity) says "Ready" (the party is started and its outgoing remotes are connected), then
       until its client applications are served. A client application whose dev server failed (its "Error") stops the
       wait: its error is printed.
    5. Prints the parties and their URLs, opens the browser on the default client application.
    6. Press Enter: the parties are stopped like Ctrl+C in their window (they stop the dev servers they started); a
       party that doesn't exit in time is killed with its process tree.

.PARAMETER SkipBuild
    Starts the parties already built.

.PARAMETER NoBrowser
    Does not open the browser.

.PARAMETER Timeout
    The seconds to wait for the parties to be ready, then for their client applications to be served. Defaults to 180.
#>
param(
    [switch] $SkipBuild,
    [switch] $NoBrowser,
    [int] $Timeout = 180
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$devFolder = $PSScriptRoot
$storeFolder = Join-Path $devFolder 'Store'

function Write-Step( [string] $text ) { Write-Host "`n==> $text" -ForegroundColor Cyan }

function Invoke-Native( [string] $what, [scriptblock] $command ) {
    & $command
    if( $LASTEXITCODE -ne 0 ) { throw "$what failed (exit code $LASTEXITCODE)." }
}

function Get-NormalizedPath( [string] $path ) { return $path.Replace( '\', '/' ).TrimEnd( '/' ) }

# The running status files, by content root. A status whose process is gone (or whose pid belongs to another process)
# is stale: it is deleted.
function Get-RunningStatuses {
    $result = @{}
    if( -not (Test-Path $storeFolder) ) { return $result }
    foreach( $f in Get-ChildItem $storeFolder -Recurse -Filter 'DevRunningStatus.json' -ErrorAction SilentlyContinue ) {
        try { $s = Get-Content $f.FullName -Raw | ConvertFrom-Json } catch { continue }
        $p = Get-Process -Id $s.ProcessId -ErrorAction SilentlyContinue
        $alive = $false
        if( $p ) {
            try { $alive = [Math]::Abs( ($p.StartTime.ToUniversalTime() - ([DateTime]$s.ProcessStartTime).ToUniversalTime()).TotalSeconds ) -lt 2 } catch { $alive = $true }
        }
        if( -not $alive ) { Remove-Item $f.FullName -ErrorAction SilentlyContinue; continue }
        if( $s.PSObject.Properties['ContentRootPath'] ) { $result[(Get-NormalizedPath $s.ContentRootPath).ToLowerInvariant()] = $s }
    }
    return $result
}

function Get-Status( [hashtable] $statuses, $party ) {
    $key = (Get-NormalizedPath $party.ProjectPath).ToLowerInvariant()
    if( $statuses.ContainsKey( $key ) ) { return $statuses[$key] }
    return $null
}

function Get-Property( $o, [string] $name ) {
    if( $o -and $o.PSObject.Properties[$name] ) { return $o.$name }
    return $null
}

# Sends Ctrl+C to the console of a process. It runs in a hidden helper process: the helper attaches to the party's
# console, ignores the signal itself and generates it for the console (a console window can't be closed from another
# process: "taskkill" without "/F" fails on a console application).
$sendCtrlC = @'
param( [int] $ProcessId )
Add-Type -Namespace Win32 -Name Console -MemberDefinition @"
[System.Runtime.InteropServices.DllImport( "kernel32.dll" )] public static extern bool FreeConsole();
[System.Runtime.InteropServices.DllImport( "kernel32.dll" )] public static extern bool AttachConsole( uint dwProcessId );
[System.Runtime.InteropServices.DllImport( "kernel32.dll" )] public static extern bool SetConsoleCtrlHandler( System.IntPtr handler, bool add );
[System.Runtime.InteropServices.DllImport( "kernel32.dll" )] public static extern bool GenerateConsoleCtrlEvent( uint dwCtrlEvent, uint dwProcessGroupId );
"@
[Win32.Console]::FreeConsole() | Out-Null
if( -not [Win32.Console]::AttachConsole( $ProcessId ) ) { exit 1 }
[Win32.Console]::SetConsoleCtrlHandler( [IntPtr]::Zero, $true ) | Out-Null
$ok = [Win32.Console]::GenerateConsoleCtrlEvent( 0, 0 )
Start-Sleep -Milliseconds 500
[Win32.Console]::FreeConsole() | Out-Null
if( $ok ) { exit 0 } else { exit 2 }
'@

# Stops a party gracefully, like Ctrl+C in its window. Its process tree is killed if it doesn't exit in time.
function Stop-Party( [System.Diagnostics.Process] $p ) {
    if( $p.HasExited ) { return }
    $command = "& { $sendCtrlC } -ProcessId $($p.Id)"
    $encoded = [Convert]::ToBase64String( [Text.Encoding]::Unicode.GetBytes( $command ) )
    Start-Process powershell -ArgumentList '-NoProfile', '-EncodedCommand', $encoded -WindowStyle Hidden -Wait
    if( -not $p.WaitForExit( 15000 ) ) {
        Write-Host "The process $($p.Id) didn't stop: its process tree is killed." -ForegroundColor Yellow
        cmd /c "taskkill /PID $($p.Id) /T /F >nul 2>&1"
    }
}

$manifests = @( Get-ChildItem (Join-Path $devFolder 'Parties') -Filter '*.json' -ErrorAction SilentlyContinue )
if( $manifests.Count -eq 0 ) { throw "No party in '$devFolder\Parties': build the solution first." }
$parties = @( $manifests | ForEach-Object {
    $m = Get-Content $_.FullName -Raw | ConvertFrom-Json
    $m | Add-Member -NotePropertyName Name -NotePropertyValue $_.BaseName -PassThru
} )
Write-Host "Parties: $(($parties | ForEach-Object Name) -join ', ')"

$running = Get-RunningStatuses
$already = @( $parties | Where-Object { Get-Status $running $_ } )
if( $already.Count -gt 0 ) { throw "Already running: $(($already | ForEach-Object Name) -join ', ')." }

if( -not $SkipBuild ) {
    foreach( $party in $parties ) {
        Write-Step "Building $($party.Name)"
        Invoke-Native "The build of $($party.Name)" { dotnet build $party.ProjectPath -v q -nologo }
    }
}

$started = @()
$previousEnvironment = $env:DOTNET_ENVIRONMENT
# The parties inherit it: the Development environment ("#Dev" is their AppIdentity environment).
$env:DOTNET_ENVIRONMENT = 'Development'
try {
    Write-Step 'Starting the parties'
    foreach( $party in $parties ) {
        # Each party runs in its own console window (its logs), from its project folder (its appsettings.json).
        if( $party.Executable -and (Test-Path $party.Executable) ) {
            $p = Start-Process -FilePath $party.Executable -WorkingDirectory $party.ProjectPath -PassThru
        }
        elseif( Test-Path $party.Dll ) {
            $p = Start-Process -FilePath 'dotnet' -ArgumentList "`"$($party.Dll)`"" -WorkingDirectory $party.ProjectPath -PassThru
        }
        else { throw "'$($party.Dll)' is missing: run this script without -SkipBuild." }
        $party | Add-Member -NotePropertyName Process -NotePropertyValue $p -Force
        $started += $p
    }

    Write-Step 'Waiting for the parties to be ready'
    $deadline = (Get-Date).AddSeconds( $Timeout )
    $pending = [System.Collections.ArrayList]@( $parties )
    while( $pending.Count -gt 0 ) {
        $statuses = Get-RunningStatuses
        foreach( $party in @( $pending ) ) {
            if( $party.Process.HasExited ) { throw "$($party.Name) stopped (see its logs)." }
            $s = Get-Status $statuses $party
            if( $s -and $s.Ready ) {
                Write-Host "$($party.Name) ($($s.FullName)) is ready."
                $party | Add-Member -NotePropertyName Status -NotePropertyValue $s -Force
                $pending.Remove( $party )
            }
        }
        if( $pending.Count -eq 0 ) { break }
        if( (Get-Date) -gt $deadline ) { throw "Not ready after $Timeout seconds: $(($pending | ForEach-Object Name) -join ', ')." }
        Start-Sleep -Milliseconds 500
    }

    Write-Step 'Waiting for the client applications (their dev servers compile them)'
    $deadline = (Get-Date).AddSeconds( $Timeout )
    do {
        $statuses = Get-RunningStatuses
        $waiting = @()
        $failed = @()
        foreach( $party in $parties ) {
            $s = Get-Status $statuses $party
            $party.Status = $s
            foreach( $c in @( Get-Property $s 'Clients' ) ) {
                if( -not $c ) { continue }
                # A client application whose dev server failed has an Error: it will never be served.
                $clientError = Get-Property $c 'Error'
                if( $clientError ) { $failed += "$($party.Name)/$($c.Name): $clientError" }
                elseif( -not $c.Serving ) { $waiting += "$($party.Name)/$($c.Name)" }
            }
        }
        if( $failed.Count -gt 0 ) { throw "Failed client applications (see the logs of their party):`n$($failed -join "`n")" }
        if( $waiting.Count -eq 0 ) { break }
        if( (Get-Date) -gt $deadline ) { throw "Not served after $Timeout seconds: $($waiting -join ', ')." }
        Start-Sleep -Seconds 1
    } while( $true )

    Write-Step 'The parties are running'
    $browserUrl = $null
    foreach( $party in $parties ) {
        $endpoints = @( Get-Property $party.Status 'Http' )
        $defaultUrl = if( $endpoints.Count -gt 0 -and $endpoints[0] ) { $endpoints[0].DefaultUrl.TrimEnd( '/' ) } else { $null }
        Write-Host "$($party.Name): $(if( $defaultUrl ) { $defaultUrl } else { '(no HTTP endpoint)' })"
        foreach( $c in @( Get-Property $party.Status 'Clients' ) ) {
            if( -not $c -or -not $defaultUrl ) { continue }
            $url = $defaultUrl + $c.RequestPath
            Write-Host "  $($c.Name): $url"
            if( $c.Kind -eq 'DefaultApp' -and -not $browserUrl ) { $browserUrl = $url }
        }
        if( -not $browserUrl -and $defaultUrl ) { $browserUrl = $defaultUrl }
    }
    if( -not $NoBrowser -and $browserUrl ) { Start-Process $browserUrl }
    Write-Host "`nPress Enter to stop the parties." -ForegroundColor Yellow
    [Console]::ReadLine() | Out-Null
}
finally {
    $env:DOTNET_ENVIRONMENT = $previousEnvironment
    [array]::Reverse( $started )
    foreach( $p in $started ) { Stop-Party $p }
    if( $started.Count -gt 0 ) { Write-Host 'The parties are stopped.' }
}
